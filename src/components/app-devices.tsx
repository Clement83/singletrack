'use client';

import { useEffect, useState } from 'react';
import { useFormatter, useTranslations } from 'next-intl';
import { Smartphone, Trash2 } from 'lucide-react';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import { PAIRING_TTL_MS } from '@/lib/app/constants';

type Device = { id: string; deviceName: string; createdAt: string; lastUsedAt: string | null };
type Pairing = { code: string; qr: string; expiresAt: string };

/** "Pair the app" (#1720): QR + short code (5 min) for the Android companion app, list of paired devices with revocation. */
export function AppDevices() {
  const t = useTranslations('userMenu.appDevices');
  const f = useFormatter();
  const [devices, setDevices] = useState<Device[]>([]);
  const [pairing, setPairing] = useState<Pairing | null>(null);
  const [pending, setPending] = useState(false);

  async function load() {
    const res = await fetch('/api/profile/app-devices').catch(() => null);
    if (res?.ok) setDevices(((await res.json()) as { devices: Device[] }).devices);
  }
  useEffect(() => {
    let live = true;
    void fetch('/api/profile/app-devices').then(async (res) => {
      if (live && res.ok) setDevices(((await res.json()) as { devices: Device[] }).devices);
    }).catch(() => undefined);
    return () => { live = false; };
  }, []);

  // The code stops being valid after 5 minutes: hide it, and refresh the list when it is used.
  useEffect(() => {
    if (!pairing) return;
    const left = new Date(pairing.expiresAt).getTime() - Date.now();
    const end = setTimeout(() => setPairing(null), Math.max(0, left));
    const poll = setInterval(() => void load(), 5000);
    return () => { clearTimeout(end); clearInterval(poll); };
  }, [pairing]);
  // A device created since the code was issued = the code was used: stop showing it.
  const shown = pairing && !devices.some((d) => new Date(d.createdAt).getTime() >= new Date(pairing.expiresAt).getTime() - PAIRING_TTL_MS) ? pairing : null;

  async function start() {
    setPending(true);
    const res = await fetch('/api/profile/app-devices', { method: 'POST' }).catch(() => null);
    setPending(false);
    if (!res?.ok) return toast.error(t('error'));
    setPairing((await res.json()) as Pairing);
  }

  async function revoke(id: string) {
    const res = await fetch('/api/profile/app-devices', { method: 'DELETE', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ id }) }).catch(() => null);
    if (!res?.ok) return toast.error(t('error'));
    setDevices((d) => d.filter((x) => x.id !== id));
    toast.success(t('revoked'));
  }

  return (
    <section className="flex flex-col gap-2">
      <h3 className="text-label uppercase text-muted-foreground">{t('title')}</h3>
      {shown ? (
        <div className="flex flex-col items-center gap-2 rounded-xl bg-muted p-3">
          {/* eslint-disable-next-line @next/next/no-img-element -- data URL generated by the server */}
          <img src={shown.qr} alt={t('qrAlt')} width={240} height={240} className="rounded-md" />
          <code className="text-lg font-medium tracking-widest" aria-label={t('code')}>{shown.code}</code>
        </div>
      ) : (
        <Button variant="outline" className="w-full justify-start" disabled={pending} onClick={() => void start()}>
          <Smartphone aria-hidden />
          {t('pair')}
        </Button>
      )}
      {devices.length > 0 && (
        <ul className="flex flex-col gap-1">
          {devices.map((d) => (
            <li key={d.id} className="flex items-center gap-2">
              <div className="min-w-0 flex-1">
                <p className="truncate text-small font-medium">{d.deviceName}</p>
                <p className="text-xs text-muted-foreground">
                  {d.lastUsedAt ? t('lastUsed', { date: f.dateTime(new Date(d.lastUsedAt), { dateStyle: 'medium' }) }) : t('neverUsed')}
                </p>
              </div>
              <Button variant="ghost" size="icon" aria-label={t('revoke', { name: d.deviceName })} onClick={() => void revoke(d.id)}>
                <Trash2 aria-hidden />
              </Button>
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}
